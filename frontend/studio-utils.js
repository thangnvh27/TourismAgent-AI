export function parseIdea(text){
  const normalized=String(text).normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/đ/g,'d').toLowerCase();
  const patch={};
  const fold=s=>s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/đ/g,'d').replace(/[^a-z0-9]+/g,' ').trim();
  const spoken=' '+fold(String(text))+' ';
  const aliases=Object.entries(catalog).flatMap(([name,entry])=>[name,...(entry.aliases||[])].map(alias=>[fold(alias),name])).sort((a,b)=>b[0].length-a[0].length);
  for(const [alias,name] of aliases) if(spoken.includes(' '+alias+' ')){patch.destination=name;break;}
  const days=normalized.match(/\b(\d{1,2})\s*ngay\b/),people=normalized.match(/\b(\d{1,2})\s*nguoi\b/),budget=normalized.match(/\b(\d+(?:[.,]\d+)?)\s*(trieu|tr|nghin|ngan)\b/);
  if(days&&Number(days[1])>=1&&Number(days[1])<=14)patch.days=Number(days[1]);
  if(people&&Number(people[1])>=1&&Number(people[1])<=20)patch.people=Number(people[1]);
  if(budget){const n=Number(budget[1].replace(',','.'))*(budget[2]==='trieu'||budget[2]==='tr'?1e6:1e3);if(n>=500000&&n<=50000000)patch.budget=n;}
  return patch;
}
export function safeDraft(data){
  if(!data||typeof data!=='object'||Array.isArray(data))return null;
  const clean={};
  const strings=['destination','transport','pace','startDate','origin'];
  const numbers=['days','people','budget','activitiesPerPersonDay','arrivalPerPerson','roomPerNight','peoplePerRoom','foodPerPersonDay','localTransportPerDay','reservePercent'];
  for(const k of strings)if(typeof data[k]==='string'&&data[k].length<=100)clean[k]=data[k];
  for(const k of numbers)if(Number.isFinite(Number(data[k]))&&data[k]!==undefined)clean[k]=Number(data[k]);
  for(const k of ['arrivalKnown','accommodationIncluded'])if(typeof data[k]==='boolean')clean[k]=data[k];
  if(Array.isArray(data.interests))clean.interests=data.interests.filter(v=>typeof v==='string'&&v.length<=80).slice(0,8);
  return Object.keys(clean).length?clean:null;
}
